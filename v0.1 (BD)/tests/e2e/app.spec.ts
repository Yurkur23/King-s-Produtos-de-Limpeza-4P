  await expect(page.getByText('Pagamento demonstrativo',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:/Confirmar Pedido/}).click()
  await expect(page.getByRole('heading',{name:'Pedido Registrado!'})).toBeVisible()
  await page.getByRole('button',{name:'Ver Meus Pedidos'}).click()
