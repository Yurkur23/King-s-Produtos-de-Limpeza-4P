test('PWA instala service worker, abre a interface offline e não guarda respostas da API em cache',async({page,context})=>{
  await page.goto('/')
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await page.reload()
  const manifest=await (await page.request.get('/manifest.webmanifest')).json()
  expect(manifest.display).toBe('standalone')
  expect(manifest.icons.some((i:{sizes:string})=>i.sizes==='512x512')).toBe(true)
  const apiCached=await page.evaluate(async()=>{
    for(const key of await caches.keys()) {
      const cache=await caches.open(key)
      if((await cache.keys()).some(r=>new URL(r.url).pathname.startsWith('/api/')))return true
    }
    return false
  })
  expect(apiCached).toBe(false)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByText(/Você está sem conexão/)).toBeVisible()
  await expect(page.getByRole('heading',{name:'Bem-vindo'})).toBeVisible()
  await context.setOffline(false)
})
